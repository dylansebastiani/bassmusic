// Turns config/catalog.json (tracks, events, coupons) into:
//   supabase/seed/catalog.sql   idempotent upserts, safe to run again
//   qr/<artist>/<track>.svg     one printable QR per track (plus one per show it is placed at)
//   qr/README.md                the list: which code is which
// A track's QR code is made once, written back into catalog.json, and never changes after that.
// `--check` validates only and writes nothing (npm run check uses it).
import { readFileSync, writeFileSync, mkdirSync, rmSync } from "node:fs";
import { join } from "node:path";
import { randomInt } from "node:crypto";

const root = new URL("..", import.meta.url).pathname;
const catPath = join(root, "config/catalog.json");
const cat = JSON.parse(readFileSync(catPath, "utf8"));
const site = JSON.parse(readFileSync(join(root, "config/stack.json"), "utf8")).siteUrl.replace(/\/$/, "");
const checkOnly = process.argv.includes("--check");
const tracks = cat.tracks ?? [], events = cat.events ?? [], coupons = cat.coupons ?? [];

const SLUG = /^[a-z0-9-]{1,80}$/, QR = /^[A-Z0-9]{6,12}$/, ALPHA = "ABCDEFGHJKLMNPQRSTUVWXYZ23456789";
const slugify = (s) => String(s || "").toLowerCase().normalize("NFKD").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
const newCode = () => Array.from({ length: 8 }, () => ALPHA[randomInt(ALPHA.length)]).join("");
const problems = [];
const bad = (m) => problems.push(m);

const seen = new Set();
for (const t of tracks) {
  if (!SLUG.test(t.slug || "")) bad(`track slug "${t.slug}" must be lowercase letters, numbers and dashes`);
  if (!t.title) bad(`track ${t.slug}: title is required`);
  if (!t.audioPath) bad(`track ${t.slug}: audioPath is required (path inside the private "drops" bucket)`);
  if (seen.has(t.slug)) bad(`duplicate track slug ${t.slug}`); seen.add(t.slug);
  if (t.qr && !QR.test(t.qr)) bad(`track ${t.slug}: qr must be 6-12 capital letters or numbers`);
}
const eslugs = new Set();
for (const e of events) {
  if (!SLUG.test(e.slug || "")) bad(`event slug "${e.slug}" must be lowercase letters, numbers and dashes`);
  if (!e.name) bad(`event ${e.slug}: name is required`);
  if (e.kind && !["show", "popup", "drop", "other"].includes(e.kind)) bad(`event ${e.slug}: kind must be show, popup, drop or other`);
  for (const k of ["startsAt", "endsAt"]) if (e[k] && Number.isNaN(Date.parse(e[k]))) bad(`event ${e.slug}: ${k} is not a date`);
  eslugs.add(e.slug);
}
for (const t of tracks) for (const p of t.placements ?? []) if (!eslugs.has(p)) bad(`track ${t.slug}: placement "${p}" is not an event in this file`);
const ccodes = new Set();
const artistSlugs = new Set(tracks.map((t) => t.artistSlug || slugify(t.artist)).filter(Boolean));
for (const c of coupons) {
  if (!c.code || !c.title) bad(`coupon needs a code and a title (${JSON.stringify(c).slice(0, 60)})`);
  if (ccodes.has(c.code)) bad(`duplicate coupon code ${c.code}`); ccodes.add(c.code);
  if (c.event && !eslugs.has(c.event)) bad(`coupon ${c.code}: event "${c.event}" is not an event in this file`);
  if (c.artist && !artistSlugs.has(c.artist)) bad(`coupon ${c.code}: artist "${c.artist}" has no track in this file (use the artistSlug)`);
}
const codes = new Set(tracks.map((t) => t.qr).filter(Boolean));
if (codes.size !== tracks.filter((t) => t.qr).length) bad("two tracks share a qr code");
if (problems.length) { console.error(problems.map((p) => "FAIL " + p).join("\n")); process.exit(1); }
if (checkOnly) { console.log(`catalog ok: ${tracks.length} tracks, ${events.length} events, ${coupons.length} coupons`); process.exit(0); }

for (const t of tracks) if (!t.qr) { let c; do c = newCode(); while (codes.has(c)); t.qr = c; codes.add(c); }
writeFileSync(catPath, JSON.stringify(cat, null, 2) + "\n");

const q = (v) => (v == null || v === "" ? "null" : "'" + String(v).replace(/'/g, "''") + "'");
const b = (v, d) => String(v ?? d);
const sql = ["-- Generated by scripts/catalog.mjs from config/catalog.json. Safe to run again.", "begin;"];
for (const t of tracks) {
  sql.push(`insert into public.drops (slug,title,artist,artist_slug,description,audio_path,artwork_path,download_path,qr_code,qr_active)
values (${q(t.slug)},${q(t.title)},${q(t.artist)},${q(t.artistSlug || slugify(t.artist))},${q(t.description)},${q(t.audioPath)},${q(t.artworkPath)},${q(t.downloadPath)},${q(t.qr)},${b(t.qrActive, true)})
on conflict (slug) do update set title=excluded.title, artist=excluded.artist, artist_slug=excluded.artist_slug, description=excluded.description,
  audio_path=excluded.audio_path, artwork_path=excluded.artwork_path, download_path=excluded.download_path, qr_active=excluded.qr_active,
  qr_code=coalesce(public.drops.qr_code, excluded.qr_code);`);
}
for (const e of events) {
  sql.push(`insert into public.events (slug,name,kind,venue,city,address,starts_at,ends_at,description,ticket_url,prize,is_active,is_public)
values (${q(e.slug)},${q(e.name)},${q(e.kind || "show")},${q(e.venue)},${q(e.city)},${q(e.address)},${q(e.startsAt)},${q(e.endsAt)},${q(e.description)},${q(e.ticketUrl)},${q(e.prize)},${b(e.active, true)},${b(e.public, true)})
on conflict (slug) do update set name=excluded.name, kind=excluded.kind, venue=excluded.venue, city=excluded.city, address=excluded.address,
  starts_at=excluded.starts_at, ends_at=excluded.ends_at, description=excluded.description, ticket_url=excluded.ticket_url, prize=excluded.prize,
  is_active=excluded.is_active, is_public=excluded.is_public;`);
}
for (const c of coupons) {
  const evId = c.event ? `(select id from public.events where slug = ${q(c.event)})` : "null";
  sql.push(`insert into public.coupons (code,title,description,url,min_tracks,event_id,artist_slug,starts_at,expires_at,is_active)
values (${q(c.code)},${q(c.title)},${q(c.description)},${q(c.url)},${Number(c.minTracks) || 0},${evId},${q(c.artist)},${q(c.startsAt)},${q(c.expiresAt)},${b(c.active, true)})
on conflict (code) do update set title=excluded.title, description=excluded.description, url=excluded.url, min_tracks=excluded.min_tracks,
  event_id=excluded.event_id, artist_slug=excluded.artist_slug, starts_at=excluded.starts_at, expires_at=excluded.expires_at, is_active=excluded.is_active;`);
}
sql.push("commit;", "");
mkdirSync(join(root, "supabase/seed"), { recursive: true });
writeFileSync(join(root, "supabase/seed/catalog.sql"), sql.join("\n"));

// QR codes. The SVG is the print file; the README says which is which.
const { default: QRCode } = await import("qrcode");
rmSync(join(root, "qr"), { recursive: true, force: true });
const rows = [];
for (const t of tracks) {
  const dir = t.artistSlug || slugify(t.artist) || "tracks";
  mkdirSync(join(root, "qr", dir), { recursive: true });
  const variants = [{ file: `${t.slug}.svg`, url: `${site}/t/${t.qr}`, where: "anywhere" }, ...(t.placements ?? []).map((p) => ({ file: `${t.slug}--${p}.svg`, url: `${site}/t/${t.qr}?e=${p}`, where: p }))];
  for (const v of variants) {
    writeFileSync(join(root, "qr", dir, v.file), await QRCode.toString(v.url, { type: "svg", margin: 2, errorCorrectionLevel: "M" }));
    rows.push(`| ${t.artist || ""} | ${t.title} | ${v.where} | \`${v.url}\` | \`qr/${dir}/${v.file}\` |`);
  }
}
writeFileSync(join(root, "qr/README.md"), ["# Track QR codes", "", "Generated by `node scripts/catalog.mjs`. Print the SVG; the URL is what it opens.", "A code tagged with a show also enters the member in that show's giveaway.", "",
  "| Artist | Track | Placed at | URL | Print file |", "|---|---|---|---|---|", ...rows, ""].join("\n"));
console.log(`wrote supabase/seed/catalog.sql and ${rows.length} QR code(s) for ${tracks.length} track(s)`);
